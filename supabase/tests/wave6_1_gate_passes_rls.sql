BEGIN;
SELECT plan(15);
SELECT has_table('public','gate_passes','gate pass table exists');
SELECT has_column('public','gate_passes','student_id','student binding exists');
SELECT has_column('public','gate_passes','qr_token','QR token exists');
SELECT has_column('public','gate_passes','due_back_at','due-back timestamp exists');
SELECT has_column('public','gate_passes','actual_back_at','actual return timestamp exists');
SELECT ok(EXISTS (SELECT 1 FROM pg_constraint c JOIN pg_class t ON t.oid=c.conrelid JOIN pg_namespace n ON n.oid=t.relnamespace WHERE n.nspname='public' AND t.relname='gate_passes' AND c.contype='u' AND c.conkey=ARRAY[(SELECT attnum FROM pg_attribute WHERE attrelid=t.oid AND attname='qr_token')]::smallint[]),'QR token is unique');
SELECT ok(EXISTS (SELECT 1 FROM pg_constraint c JOIN pg_class t ON t.oid=c.conrelid JOIN pg_namespace n ON n.oid=t.relnamespace WHERE n.nspname='public' AND t.relname='gate_passes' AND c.contype='c' AND pg_get_constraintdef(c.oid) LIKE '%pending%approved%out%returned%overdue%rejected%cancelled%'),'status is constrained');
SELECT has_function('public','request_gate_pass',ARRAY['uuid','text','text','timestamptz'],'request RPC exists');
SELECT has_function('public','approve_gate_pass',ARRAY['uuid','boolean'],'approval RPC exists');
SELECT has_function('public','scan_gate_pass',ARRAY['text','text'],'scan RPC exists');
SELECT has_function('public','refresh_gate_pass_overdue',ARRAY[]::text[],'overdue RPC exists');
SELECT ok((SELECT relrowsecurity FROM pg_class WHERE oid='public.gate_passes'::regclass),'gate pass RLS enabled');
SELECT ok(NOT has_table_privilege('anon','public.gate_passes','SELECT'),'anon cannot select gate passes');
SELECT ok(has_table_privilege('authenticated','public.gate_passes','SELECT'),'authenticated select is RLS-gated');
SELECT ok(NOT has_table_privilege('authenticated','public.gate_passes','INSERT'),'authenticated direct insert is revoked; requests use RPC');
SELECT * FROM finish();
ROLLBACK;
